var table = {}
for (var key in source) {
    var value = source[key]
    // Single-letter values alias a Latin look-alike.
    table[key] = value.length === 1 ? source[value].split("|") : value.split("|")
}

// Uppercases and strips diacritics so "R\u00E9duction" still renders on the grid.
function normalize(text) {
    return text.toUpperCase().normalize("NFD").replace(/[\u0300-\u036F]/g, "").replace(/\u1E9E|\u00DF/g, "SS")
}
